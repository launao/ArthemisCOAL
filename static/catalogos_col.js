// TYPEAHEAD ENGINE — búsqueda rápida en catálogos
// ═══════════════════════════════════════════════════════════════════
var Typeahead = (function(){
  function normalize(s){ return (s||'').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,''); }

  function search(list, q, keyFn, max){
    max = max || 15;
    if(!q || q.length < 2) return [];
    var nq = normalize(q);
    var tokens = nq.split(/\s+/);
    var scored = [];
    for(var i=0;i<list.length;i++){
      var item = list[i];
      var text = normalize(keyFn(item));
      var match = true;
      for(var t=0;t<tokens.length;t++){
        if(text.indexOf(tokens[t]) === -1){ match=false; break; }
      }
      if(!match) continue;
      // Score: exact start = 100, word start = 50, contains = 10
      var score = 10;
      if(text.indexOf(nq) === 0) score = 100;
      else if(text.indexOf(nq) > -1) score = 50;
      scored.push({item:item, score:score});
    }
    scored.sort(function(a,b){ return b.score - a.score; });
    return scored.slice(0, max).map(function(s){ return s.item; });
  }

  function searchCIE10(q){ return search(CIE10, q, function(x){ return x.c+' '+x.d; }); }
  function searchCUPS(q, tipo){
    var filtered = tipo ? CUPS.filter(function(x){ return x.t === tipo; }) : CUPS;
    return search(filtered, q, function(x){ return x.c+' '+x.d; });
  }
  function searchMeds(q){ return search(MEDICAMENTOS_INVIMA, q, function(x){ return x.n+' '+x.cum+' '+(x.conc||[]).join(' '); }); }
  function searchEsp(q){ return search(ESPECIALIDADES, q, function(x){ return x; }, 10); }

  // Create a typeahead dropdown component
  function create(inputEl, searchFn, renderFn, onSelectFn){
    var wrap = document.createElement('div');
    wrap.style.cssText = 'position:relative;';
    inputEl.parentNode.insertBefore(wrap, inputEl);
    wrap.appendChild(inputEl);

    var dd = document.createElement('div');
    dd.style.cssText = 'position:absolute;top:100%;left:0;right:0;z-index:1000;background:#fff;border:1px solid #E6E1D8;border-radius:8px;max-height:240px;overflow-y:auto;display:none;box-shadow:0 4px 12px rgba(0,0,0,.12);';
    wrap.appendChild(dd);

    var debounce = null;
    inputEl.addEventListener('input', function(){
      clearTimeout(debounce);
      debounce = setTimeout(function(){
        var q = inputEl.value.trim();
        var results = searchFn(q);
        if(!results.length){ dd.style.display='none'; return; }
        dd.innerHTML = '';
        results.forEach(function(r){
          var opt = document.createElement('div');
          opt.style.cssText = 'padding:8px 12px;cursor:pointer;font-size:13px;border-bottom:1px solid #f0f0f0;transition:background .1s;';
          opt.innerHTML = renderFn(r);
          opt.addEventListener('mouseenter', function(){ this.style.background='#EDF4F7'; });
          opt.addEventListener('mouseleave', function(){ this.style.background=''; });
          opt.addEventListener('mousedown', function(e){
            e.preventDefault();
            onSelectFn(r);
            dd.style.display = 'none';
          });
          dd.appendChild(opt);
        });
        dd.style.display = 'block';
      }, 200);
    });

    inputEl.addEventListener('blur', function(){
      setTimeout(function(){ dd.style.display='none'; }, 200);
    });

    inputEl.addEventListener('focus', function(){
      if(inputEl.value.trim().length >= 2){
        inputEl.dispatchEvent(new Event('input'));
      }
    });

    return { destroy: function(){ wrap.parentNode.insertBefore(inputEl, wrap); wrap.remove(); } };
  }

  return {
    searchCIE10: searchCIE10,
    searchCUPS: searchCUPS,
    searchMeds: searchMeds,
    searchEsp: searchEsp,
    create: create,
    normalize: normalize
  };
})();
